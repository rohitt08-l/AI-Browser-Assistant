#!/usr/bin/env bash
# Package the Chrome extension as a store-ready zip.
# Usage: scripts/package-extension.sh [BACKEND_URL] [OUT_DIR]
set -euo pipefail

BACKEND_URL="${1:-}"
OUT_DIR="${2:-dist}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
VERSION="$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["version"])' "$ROOT/extension/manifest.json")"
BUILD="$(mktemp -d)"
trap 'rm -rf "$BUILD"' EXIT

cp -R "$ROOT/extension/." "$BUILD/"
find "$BUILD" -name '*.map' -delete

if [[ -n "$BACKEND_URL" ]]; then
  BACKEND_URL="${BACKEND_URL%/}"
  [[ "$BACKEND_URL" =~ ^https?://[^\"\'[:space:]]+$ ]] || { echo "Invalid BACKEND_URL: $BACKEND_URL" >&2; exit 1; }
  printf '// Generated by scripts/package-extension.sh\nconst DEFAULT_BACKEND = "%s";\n' "$BACKEND_URL" > "$BUILD/config.js"
fi

mkdir -p "$OUT_DIR"
ZIP="$(cd "$OUT_DIR" && pwd)/ai-web-assistant-v${VERSION}.zip"
rm -f "$ZIP"
(cd "$BUILD" && zip -qr -X "$ZIP" .)
echo "$ZIP"
